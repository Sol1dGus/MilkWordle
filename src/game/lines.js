export function line(key, vars = {}, seed = null) {
  const arr = LINES[key] || ['Му?'];
  let text;
  if (seed == null) {
    text = pick(arr);
  } else {
    // детерминированный выбор: одинаковый seed — одна и та же фраза у всех
    let h = 0;
    const s = String(seed) + key;
    for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
    text = arr[h % arr.length];
  }
  for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`%${k}%`, v);
  return text;
}

// Какую реплику сказать соло-игроку по качеству попытки
export function soloLineFor(marks) {
  const greens = marks.filter((m) => m === 'correct').length;
  const yellows = marks.filter((m) => m === 'present').length;
  if (greens === 5) return null; // победа обрабатывается отдельно
  if (greens >= 3 || greens + yellows >= 4) return 'hot';
  if (greens + yellows >= 2) return 'warm';
  return 'cold';
}
