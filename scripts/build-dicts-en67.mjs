async function fetchText(urls) {
  for (const url of urls) {
    try {
      const r = await fetch(url, { signal: AbortSignal.timeout(30000) });
      if (r.ok) return await r.text();
    } catch {
      /* пробуем следующий источник */
    }
  }
  return null;
}

